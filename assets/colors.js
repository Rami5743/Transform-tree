/** ממירה ערך צבע בקוד ויקי לצבע CSS, לצורך התצוגה המקדימה. */
export function toCss(value, fallback = 'black') {
  if (value === null || value === undefined) return fallback;
  const v = String(value).trim();
  if (!v) return fallback;
  let m = /^\{\{\s*תרשים\/הגדרות\s*\|\s*([^|}]+?)\s*\}\}$/.exec(v);
  if (m) return PRESETS[m[1]] || fallback;
  m = /^\{\{\s*איכ\s*\|\s*(\d+)\s*\|\s*(\d+)\s*\|\s*(\d+)\s*\}\}$/.exec(v);
  if (m) return `rgb(${m[1]},${m[2]},${m[3]})`;
  if (PLAIN[v]) return PLAIN[v];
  if (/^[#a-zA-Z0-9(),.%\s-]+$/.test(v)) return v;
  return fallback;
}
