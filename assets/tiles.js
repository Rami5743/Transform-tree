/*
 * tiles.js — מודל המרצפות.
 *
 * כל מרצפת מתוארת על ידי ארבעה "קטעים" היוצאים ממרכז המרצפת לארבעת
 * הכיוונים. הכיוונים מסומנים באותיות u (למעלה), d (למטה), l (שמאלה),
 * r (ימינה), ובתבנית {{מרצפת}} הם מיוצגים על ידי הספרות 8, 2, 4, 6.
 *
 * קטע הוא null (אין קו) או אובייקט { s, col }:
 *   s   – סגנון הקו: 'solid' או 'dashed'
 *   col – צבע הקו: מחרוזת, או null עבור צבע בררת המחדל (שחור)
 *
 * המודל הזה נשאב מקוד המקור של {{עץ משפחה}} ושל {{מרצפת}} בוויקיפדיה
 * העברית, והוא מה שמאפשר לתרגם *כל* מרצפת – גם כאלה שאין להן מקבילה
 * ישירה בתבנית {{מרצפת}} (הן מתורגמות למרצפת האוניברסלית).
 */

export const DIRS = ['u', 'd', 'l', 'r'];

/** הספרה שבה תבנית {{מרצפת}} מסמנת כל כיוון (מקלדת נומרית). */
export const DIR_DIGIT = { u: '8', d: '2', l: '4', r: '6' };

/**
 * פענוח תיאור מקוצר של מרצפת, למשל "u d ~l =r":
 *   ~ לפני הכיוון – הקו מקווקו
 *   = לפני הכיוון – הקו נצבע בצבע המשני (צבע2)
 */
function spec(str) {
  const segs = { u: null, d: null, l: null, r: null };
  for (const tok of str.split(/\s+/).filter(Boolean)) {
    const dashed = tok.includes('~');
    const second = tok.includes('=');
    const dir = tok.replace(/[~=]/g, '');
    if (!DIRS.includes(dir)) throw new Error('כיוון לא מוכר: ' + tok);
    segs[dir] = { s: dashed ? 'dashed' : 'solid', slot: second ? 'צבע2' : 'צבע' };
  }
  return segs;
}

